CREATE VIEW public.v_city_inventory WITH (security_invoker=true) AS SELECT d.market,
    d.city,
    sc.concept,
    count(*) AS n_deals,
    min(d.price_usd) AS min_price,
    percentile_cont((0.5)::double precision) WITHIN GROUP (ORDER BY ((d.price_usd)::double precision)) AS median_price,
    max(d.price_usd) AS max_price
   FROM (public.deals d
     JOIN public.service_concepts sc ON (((sc.market = d.market) AND (sc.title = d.title))))
  WHERE (sc.concept IS NOT NULL)
  GROUP BY d.market, d.city, sc.concept;

COMMENT ON VIEW public.v_city_inventory IS 'What is stocked where, at CONCEPT grain — the grain the cross-city gate operates at. median_price drives S6a: the gate suppresses the cross-city offer below $100.';

